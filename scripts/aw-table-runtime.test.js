const assert = require('node:assert/strict');
const { planActions, planActionColumn, reduceQuery, createRequestCoordinator } = require('../project/demos/aw-table');
const action = (key, width = 40, extra = {}) => ({ key, width, ...extra });
const normal = Array.from({ length: 5 }, (_, n) => action(String(n)));
for (let n = 0; n <= 5; n++) {
  const plan = planActions(normal.slice(0, n), 600, 40, 8);
  const inlineCount = n > 3 ? 2 : n;
  assert.equal(plan.inline.length, inlineCount);
  assert.equal(plan.overflow.length, n - inlineCount);
  assert.ok(plan.inline.length + Number(plan.overflow.length > 0) <= 3, 'More counts as one of three visible entries');
  if (n === 0) assert.equal(plan.width, 0, 'no empty action column');
}
const three = planActions(normal.slice(0, 3), 168, 40, 8);
assert.equal(three.inline.length, 3, 'exactly fitting three actions stay inline');
const narrow = planActions(normal.slice(0, 3), 150, 40, 8);
assert.equal(narrow.inline.length, 1, 'More also consumes width, so two plus More do not fit');
assert.equal(narrow.width, 120);
const long = planActions([action('long', 240), action('other')], 90, 80, 8);
assert.equal(long.inline.length, 1);
assert.equal(long.width, 360, 'primary plus More returns true minimum for growth and scrolling');
assert.equal(planActions(normal.slice(0, 3), 168, 40, 8).inline.length, 3, 'widening restores actions without accumulated state');
const mixed = planActions([action('hidden', 500, { hidden: true }), action('disabled', 45, { disabled: true }), action('danger', 40, { danger: true })], 600, 40, 8);
assert.deepEqual(mixed.inline.map(a => a.key), ['disabled']);
assert.deepEqual(mixed.overflow.map(a => a.key), ['danger']);
assert.equal(mixed.width, 125);
assert.equal(planActions([action('danger', 40, { danger: true })], 600, 40, 8).inline.length, 0);
const taskActions = [action('details'), action('pause'), action('logs'), action('terminate', 40, { danger: true })];
const taskPlan = planActions(taskActions, 600, 40, 8);
assert.deepEqual(taskPlan.inline.map(a => a.key), ['details', 'pause'], 'a danger menu reserves the third visible entry');
assert.deepEqual(taskPlan.overflow.map(a => a.key), ['logs', 'terminate'], 'operation logs fold before danger actions');
assert.equal(taskPlan.width, 168, 'column measurement includes two actions and More, not a fourth entry');
const membershipException = action('removeMember', 40, { danger: true, inlineException: 'group-membership-removal' });
assert.equal(planActions([membershipException], 600, 40, 8).inline.length, 1, 'a registered danger exception may remain inline');
const exceptionPlan = planActions(normal.slice(0, 3).concat(membershipException), 600, 40, 8);
assert.equal(exceptionPlan.inline.length, 2, 'registered inline exceptions do not bypass the entry cap');
assert.equal(exceptionPlan.inline.length + Number(exceptionPlan.overflow.length > 0), 3);
const query = { page: 3, pageSize: 20, search: 'draft', status: '', sort: '' };
assert.equal(reduceQuery(query, { type: 'page', value: 3 }), query, 'no-op keeps identity, emits no query commit');
assert.deepEqual(reduceQuery(query, { type: 'pageSize', value: 50 }), { ...query, page: 1, pageSize: 50 });
assert.deepEqual(reduceQuery(query, { type: 'sort', value: 'asc' }), { ...query, page: 1, sort: 'asc' });
assert.deepEqual(reduceQuery(query, { type: 'filter', search: 'new', status: 'draft' }), { ...query, page: 1, search: 'new', status: 'draft' });
assert.equal(query.page, 3, 'controlled query is not mutated');
const filterQuery = { page: 3, pageSize: 50, search: '', model: '', status: '', version: '', createdRange: ['', ''], sort: 'desc' };
const appliedFilters = { search: 'sample', model: 'K1352', status: 'published', version: '1.2.', createdRange: ['2026-10-01', '2026-10-21'] };
const applied = reduceQuery(filterQuery, { type: 'filter', ...appliedFilters });
assert.deepEqual(applied, { ...filterQuery, ...appliedFilters, page: 1 }, 'a filter commit updates all declared fields together and resets the page');
assert.equal(reduceQuery(applied, { type: 'filter', ...appliedFilters, createdRange: [...appliedFilters.createdRange] }), applied, 'identical normalized filters emit no duplicate query commit even with a new range array');
assert.deepEqual(reduceQuery(applied, { type: 'filter', search: 'next' }), { ...applied, search: 'next' }, 'partial filter events preserve unrelated applied fields');
assert.deepEqual(filterQuery.createdRange, ['', ''], 'query reduction does not mutate the prior range');
const searched = reduceQuery(filterQuery, { type: 'search', values: appliedFilters });
assert.deepEqual(searched, { ...filterQuery, ...appliedFilters, page: 1 }, 'Search applies all filters and resets the page only when filters change');
const laterPage = { ...searched, page: 3 };
assert.equal(reduceQuery(laterPage, { type: 'search', values: { ...appliedFilters, createdRange: [...appliedFilters.createdRange] } }), laterPage, 'same-condition Search preserves the page and query identity; the request layer still refreshes');
assert.deepEqual(reduceQuery(laterPage, { type: 'search', values: { ...appliedFilters, model: 'P10' } }), { ...laterPage, model: 'P10', page: 1 }, 'a changed model returns to the first page without losing other query values');
assert.deepEqual(reduceQuery(laterPage, { type: 'search', values: { ...appliedFilters, createdRange: ['2026-10-02', '2026-10-21'] } }), { ...laterPage, createdRange: ['2026-10-02', '2026-10-21'], page: 1 }, 'date-range changes are compared by values');
assert.equal(reduceQuery(laterPage, { type: 'search', values: { ...appliedFilters, page: 99, pageSize: 200, sort: 'asc' } }), laterPage, 'filter values cannot overwrite pagination or sorting');
assert.equal(laterPage.page, 3, 'Search never mutates the previous query');

const initialQuery = { page: 1, pageSize: 20, search: '', model: '', status: '', version: '', createdRange: ['', ''], sort: '' };
assert.deepEqual(reduceQuery(applied, { type: 'reset', values: initialQuery }), initialQuery, 'reset restores paging, sorting and every filter in one transition');
assert.equal(reduceQuery(initialQuery, { type: 'reset', values: initialQuery }), initialQuery, 'an unchanged reset emits no query commit');

console.log('AWTable action layout and query transitions passed');

// Request acceptance is synchronous; stale error/finally cannot unlock a new read.
const owner = createRequestCoordinator();
assert.equal(owner.accept(initialQuery, 'A', 'waiting'), null);
assert.equal(owner.accept(initialQuery, 'A', 'blocked'), null);
const firstRead = owner.accept(initialQuery, 'A', 'ready');
assert.equal(owner.pending(), true);
assert.equal(owner.accept({ ...initialQuery, page: 2 }, 'A', 'ready'), null, 'pending foreground request rejects duplicate intents');
assert.notEqual(firstRead.query, initialQuery, 'requests own an immutable query snapshot');
assert.notEqual(firstRead.query.createdRange, initialQuery.createdRange);
owner.invalidate();
const newerRead = owner.accept({ ...initialQuery, page: 2 }, 'B', 'ready');
assert.equal(owner.isCurrent(firstRead), false);
assert.equal(owner.settle(firstRead), false, 'old finally must not release the new request');
assert.equal(owner.pending(), true);
assert.equal(owner.isCurrent(newerRead), true);
assert.equal(owner.settle(newerRead), true);
assert.equal(owner.pending(), false);
assert.ok(newerRead.id > firstRead.id);
const actionCombinations = [normal.slice(0, 1), normal.slice(0, 3), normal, [action('long', 240), action('other')]];
const budget = planActionColumn(actionCombinations, 600, 40, 8);
assert.equal(budget, Math.max(...actionCombinations.map(items => planActions(items, 600, 40, 8).width)));
assert.equal(planActionColumn([...actionCombinations].reverse(), 600, 40, 8), budget, 'page ordering cannot change the declared action budget');
console.log('AWTable synchronous request ownership and declared action budgets passed');
